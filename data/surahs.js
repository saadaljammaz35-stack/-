/** صفحة بداية الجزء (١..٣٠) */
export function juzStartPage(juz) {
  return juz <= 1 ? 1 : 2 + (juz - 1) * 20;
}

/** رقم الجزء الذي تقع فيه الصفحة */
export function pageToJuz(page) {
  if (page <= 1) return 1;
  return Math.min(30, Math.floor((page - 2) / 20) + 1);
}

/** السورة التي تبدأ عندها الصفحة أو التي تحتويها */
export function pageToSurah(page) {
  let found = SURAHS[0];
  for (const s of SURAHS) {
    if (s.page <= page) found = s; else break;
  }
  return found;
}
