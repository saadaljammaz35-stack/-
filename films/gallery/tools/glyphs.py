"""Shapes Arabic lines with HarfBuzz and writes their outlines as SVG path data
(font units, y up) for the gallery film's extruded 3D type.

    python glyphs.py ../../fonts ../glyphs.js
"""
import json
import os
import sys

import uharfbuzz as hb
from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.pens.transformPen import TransformPen
from fontTools.ttLib import TTFont

LINES = {
    'prompt': ('plex-arabic-600.woff2', ['أبي موقع ثلاثي الأبعاد،', 'فخم ويتحرك مع اللي يتصفحه،', 'ويبهر من أول نظرة']),
    'tagline': ('plex-arabic-500.woff2', ['استوديو تجارب رقمية']),
}


def shape(font_path, text):
    tt = TTFont(font_path)
    tt.flavor = None
    import io
    buf = io.BytesIO()
    tt.save(buf)
    data = buf.getvalue()
    face = hb.Face(data)
    font = hb.Font(face)
    b = hb.Buffer()
    b.add_str(text)
    b.guess_segment_properties()
    hb.shape(font, b, {'kern': True, 'liga': True})
    gs = tt.getGlyphSet()
    order = tt.getGlyphOrder()
    pen = SVGPathPen(gs)
    x = 0
    missing = 0
    for info, pos in zip(b.glyph_infos, b.glyph_positions):
        name = order[info.codepoint]
        if info.codepoint == 0:
            missing += 1
        tp = TransformPen(pen, (1, 0, 0, 1, x + pos.x_offset, pos.y_offset))
        gs[name].draw(tp)
        x += pos.x_advance
    return {'d': pen.getCommands(), 'width': x, 'upm': tt['head'].unitsPerEm, 'missing': missing}


def main(font_dir, out):
    res = {}
    for key, (fname, lines) in LINES.items():
        res[key] = []
        for line in lines:
            g = shape(os.path.join(font_dir, fname), line)
            print(key, repr(line), 'width', g['width'], 'missing', g['missing'], 'len', len(g['d']))
            res[key].append({'text': line, 'd': g['d'], 'width': g['width'], 'upm': g['upm']})
    with open(out, 'w') as f:
        f.write('// Generated by tools/glyphs.py (HarfBuzz-shaped IBM Plex Sans Arabic outlines, font units, y up).\n')
        f.write('window.GLYPHS = ' + json.dumps(res, ensure_ascii=False) + ';\n')


if __name__ == '__main__':
    main(sys.argv[1], sys.argv[2])
