import { createRequire } from 'node:module';
const require = createRequire(import.meta.url);
const { chromium } = require('playwright');
import path from 'node:path';
const HERE = path.dirname(new URL(import.meta.url).pathname);
const b = await chromium.launch();
const p = await b.newPage({ viewport: { width: 1080, height: 1080 }, deviceScaleFactor: 1 });
p.on('pageerror', e => console.log('ERR', e.message));
await p.goto('file://' + path.join(HERE, 'film.html'));
await p.evaluate(() => window.filmReady);
const out = await p.evaluate(() => {
  const R = {};
  const r = el => { const b = el.getBoundingClientRect(); return [Math.round(b.left), Math.round(b.top), Math.round(b.right), Math.round(b.bottom)]; };
  seek(40);
  R.LOCK_S = +window.__LS.toFixed(4); R.DISC_CX = +window.__DCX.toFixed(1);
  R.lock = r(document.getElementById('s1lock'));
  R.pill = r(document.getElementById('s1pill'));
  R.cardtxt = r(document.getElementById('s1cardtxt'));
  seek(158);
  R.tintOpacity = document.getElementById('s3tint').style.opacity;
  seek(150);
  R.date = r(document.getElementById('s3date'));
  R.glass = r(document.getElementById('s3glass'));
  seek(180);
  R.lesson = r(document.getElementById('lesson'));
  R.key = r(document.querySelector('#lbody .key'));
  R.body = r(document.getElementById('lbody'));
  seek(230);
  R.c6a = r(document.getElementById('c6a'));
  R.titleA = r(document.getElementById('c6at'));
  R.titleB = r(document.getElementById('c6bt'));
  R.fsA = document.getElementById('c6at').style.fontSize;
  R.fsB = document.getElementById('c6bt').style.fontSize;
  return R;
});
console.log(JSON.stringify(out, null, 1));
await b.close();
